#define VBE_SET_MODE 0x4F02
#define VBE_CURRENT_MODE 0x4F03
#define VBE_SAVE_RESTORE_STATE 0x4F04
#define VBE_DISPLAY_WINDOW_CTRL 0x4F05
#define VBE_SET_GET_LOGICAL_SCAN_L_LEN 0x4F06
#define VBE_SET_GET_DISPLAY_START 0x4F07
#define VBE_SET_GET_DAC_PALLETE_FORMAT 0x4F08
